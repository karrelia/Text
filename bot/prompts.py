AUDIO_TRANSCRIBE_PROMPT = """\
Розшифруй це аудіо дослівно. Мовлення переважно українською, можливий суржик \
із російською та вкраплення англійських термінів і назв.

- Пиши точно те, що прозвучало, включно із запинками й повторами. Редагування \
буде окремим кроком.
- Англійські слова, назви та абревіатури пиши латиницею.
- Нерозбірливі місця познач як [нерозбірливо].
- Не перекладай, не переказуй і не коментуй.
- У відповідь надішли лише текст розшифровки.\
"""


def build_whisper_hint(glossary: str = "") -> str:
    """Підказка для Whisper API: задає стиль запису та власні назви.

    Whisper використовує prompt як «продовження попереднього тексту», тому
    підказка має виглядати як зразок бажаного письма, а не як інструкція.
    """
    hint = "Розшифровка українською мовою з англійськими термінами та назвами."
    if glossary.strip():
        terms = ", ".join(
            part.strip() for part in glossary.replace("\n", ",").split(",") if part.strip()
        )
        if terms:
            hint += f" Власні назви: {terms}."
    # Whisper обрізає підказку приблизно на 224 токенах — тримаємось у межах.
    return hint[:900]
