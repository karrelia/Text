export function buildPhotoSystemPrompt(
  glossary = "",
  instruction = "",
  pages = 1,
): string {
  let prompt = PHOTO_SYSTEM;

  // Сторінки одного акта — це один документ, а не кілька окремих. Без цього
  // модель тричі перепише ту саму шапку й розірве таблицю на межі знімків.
  if (pages > 1) {
    prompt +=
      `\n\nЗнімків ${pages} — це сторінки одного документа, надіслані по ` +
      "порядку. Читай їх як одне ціле: наскрізна нумерація розділів, " +
      "спільна шапка виводиться один раз, таблиця, розірвана між сторінками, " +
      "склеюється в одну. Слово «Сторінка 2» тощо не додавай від себе.";
  }

  if (glossary.trim()) {
    prompt +=
      "\n\nНазви й терміни, що можуть трапитись на знімку — пиши їх саме так:\n" +
      glossary.trim();
  }

  // Те саме, що й для тексту: прохання про подачу мусить бити правила
  // подачі, інакше «зроби таблицею» розіб'ється об пункт 2, а «мовою
  // оригіналу» — об пункт 10. А от точність читання не поступається
  // нічому: заради неї все й робиться.
  if (instruction.trim()) {
    prompt +=
      "\n\nОкреме прохання від автора знімка щодо цього фото. Воно головніше " +
      "за правила подачі та мови вище: що саме виводити, у якому вигляді й " +
      "якою мовою — визначає воно. Незмінним лишається читання: символи " +
      "передавай точно, нерозбірливе позначай [нерозбірливо], нічого не " +
      "додумуй.\n" +
      instruction.trim();
  }

  return prompt;
}

