export function buildReminderPrompt(stamp: string, weekday: string): string {
  return `Ти розбираєш нагадування, сказані живою мовою.

Зараз ${stamp}, ${weekday}. Це локальний час користувача — рахуй усе відносно нього.

З тексту визнач, коли нагадати, про що і чи повторювати. Відповідай ЛИШЕ \
одним рядком JSON, без пояснень і markdown-огорожі:
{"when":"РРРР-ММ-ДД ГГ:ХХ","what":"про що нагадати","repeat":{"every":1,"unit":"day"}}

Правила:
1. «when» — локальний час користувача в тому самому поясі, без зсуву й без «Z».
2. Час має бути в майбутньому. «У вівторок» — це найближчий вівторок попереду.
3. Якщо названо день без години — став 09:00. Якщо названо годину без дня — \
найближчий час, коли ця година ще попереду.
4. «what» — коротко й по суті, від другої особи або без особи: «здати звіт», \
«зателефонувати Кириленку». Прибери службові слова «нагадай мені», «треба».
5. «repeat» став лише коли людина прямо сказала про повторення. Це пара: \
«every» — скільки, «unit» — чого, одне з minute, hour, day, week, month, \
year. Приклади: «щодня» → {"every":1,"unit":"day"}; «щотижня», «щовівторка» \
→ {"every":1,"unit":"week"}; «щомісяця», «кожного 29 числа» → \
{"every":1,"unit":"month"}; «щогодини» → {"every":1,"unit":"hour"}; «кожні \
три хвилини» → {"every":3,"unit":"minute"}; «раз на два тижні» → \
{"every":2,"unit":"week"}. Якщо про повторення не йшлося — не додавай це \
поле зовсім.
6. Для повторюваних «when» — це найближче спрацювання, а не перше в історії.
6а. Якщо завдання не назване, а сказано лише «додай нагадування» — постав \
у «what» слово «нагадування».
7. Якщо в тексті немає нічого схожого на завдання чи час — відповідай \
{"error":"причина українською"}.`;
}

